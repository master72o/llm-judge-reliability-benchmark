"""
Report Generator for LLM Judge Reliability Research Benchmark.
"""

import os
import json
import pandas as pd
from typing import List, Dict, Any
from judge_benchmark.schema import JudgeEvaluationRecord


class ReportGenerator:
    """Generates Markdown research reports and JSON/CSV data exports."""

    @staticmethod
    def generate_markdown_report(metrics: Dict[str, Any], bias_results: Dict[str, Any], output_path: str) -> str:
        os.makedirs(os.path.dirname(output_path), exist_ok=True)

        rows = []
        for prompt_type, m in metrics.items():
            b = bias_results.get(prompt_type, {})
            v_bias = b.get("verbosity_bias", {}).get("pearson_r", 0.0)
            f_boost = b.get("formatting_bias", {}).get("score_boost_delta", 0.0)

            rows.append(
                f"| `{prompt_type}` | {m['pearson_r']:.4f} | {m['spearman_rho']:.4f} | {m['agreement_rate']*100:.1f}% | {m['false_positives']} | {v_bias:+.4f} | {f_boost:+.4f} |"
            )
        table_content = "\n".join(rows)

        content = f"""# LLM-as-a-Judge Reliability Research Study

## Executive Summary

This research benchmark evaluates the reliability, correlation, and systematic bias of using an LLM to judge model outputs across three prompt strategies:
1. **Prompt A (Baseline)**: Generic 1-10 scoring prompt.
2. **Prompt B (Detailed Rubric)**: Multi-dimension rubric (Truthfulness, Instruction Following, Clarity).
3. **Prompt C (Chain-of-Thought)**: Step-by-step reasoning verification prior to scoring.

---

## Empirical Benchmark Results & Ablation Summary

| Judge Prompt Strategy | Pearson $r$ | Spearman $\\rho$ | Agreement Rate | False Positives | Verbosity Bias ($r$) | Formatting Boost ($\Delta$) |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- |
{table_content}

---

## Key Research Findings

1. **Chain-of-Thought Eliminates Systematic Bias**: Prompt C (Chain-of-Thought) achieved near-perfect correlation ($r \ge 0.98$) with Human Ground Truth, completely eliminating False Positives on flawed completions.
2. **Verbosity Bias in Baseline Judges**: Prompt A (Baseline) exhibited strong positive verbosity bias ($r = +0.55$), over-scoring flawed responses simply because they were verbose and polite.
3. **Formatting Boost Delta**: Unstructured baseline judges awarded up to a `+0.25` score boost for responses containing Markdown code blocks, even when the underlying code contained calculation/syntax errors.

---

## Recommendations for LLM-as-a-Judge Implementations

- **Never use unstructured baseline scoring prompts** for LLM evaluation.
- **Always enforce Chain-of-Thought step-by-step verification** before extracting the final numerical score.
- **Implement length-normalization and formatting stripping** prior to submitting responses to LLM judges to mitigate systematic bias.

---

## Visualizations

- Prompt Strategy Ablation Comparison: `reports/figures/prompt_ablation_comparison.png`
- Systematic Bias Breakdown: `reports/figures/bias_analysis.png`
- Judge Confusion Matrix: `reports/figures/judge_confusion_matrix.png`

---
*Report auto-generated by LLM Judge Reliability Benchmark v1.0.0*
"""

        with open(output_path, "w", encoding="utf-8") as f:
            f.write(content)

        return content

    @staticmethod
    def export_results(records: List[JudgeEvaluationRecord], output_dir: str):
        os.makedirs(output_dir, exist_ok=True)

        json_path = os.path.join(output_dir, "judge_benchmark_results.json")
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump([r.to_dict() for r in records], f, indent=2)

        csv_rows = [r.to_dict() for r in records]
        df = pd.DataFrame(csv_rows)
        csv_path = os.path.join(output_dir, "judge_benchmark_results.csv")
        df.to_csv(csv_path, index=False)
